/** Picks a raw-string delimiter that does not occur in the payload. */
export function rRawString(s: string): string {
  let dashes = "-";
  while (s.includes(`)${dashes}"`)) dashes += "-";
  return `r"${dashes}(${s})${dashes}"`;
}

/**
 * A self-contained R script that rebuilds the same analysis specification with
 * the official R APIs. It embeds r/strategus-from-ir.R verbatim (passed in as
 * `rSource`), which is the same code CI uses to produce the golden output.
 * Use buildRScript from ./rScriptBundled in the browser.
 */
