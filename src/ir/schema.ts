/** Concepts of a template cohort; phenotype cohorts carry theirs inside the Circe definition. */
export function cohortConcepts<T extends { kind: string; concepts?: unknown[] }>(c: T): NonNullable<T["concepts"]> {
  return (c.kind === "phenotype" ? [] : (c.concepts ?? [])) as NonNullable<T["concepts"]>;
}
export const DraftStudyIRSchema = draft.study;
export type DraftStudyIR = z.infer<typeof DraftStudyIRSchema>;

export function parseStudyIR(input: unknown) {
  return StudyIRSchema.safeParse(input);
}

/** JSON Schema of the IR (fully resolved). */
export function studyIRJsonSchema() {
  return z.toJSONSchema(StudyIRSchema, { io: "input" });
}

/** Drops JSON Schema noise from z.number().int() (safe-integer bounds). */
function stripSafeIntegerBounds(value: unknown): unknown {
  if (Array.isArray(value)) return value.map(stripSafeIntegerBounds);
  if (value && typeof value === "object") {
    return Object.fromEntries(
      Object.entries(value)
        .filter(([k, v]) => !((k === "maximum" || k === "minimum") && Math.abs(v as number) === Number.MAX_SAFE_INTEGER))
        .map(([k, v]) => [k, stripSafeIntegerBounds(v)]),
    );
  }
  return value;
}

/**
 * JSON Schema embedded in the LLM prompt: concepts are always unresolved and
 * repeated parts (cohorts, concepts) are shared through $defs to keep it short.
 * Parsing still uses DraftStudyIRSchema, which also accepts resolved concepts.
 */
export function draftStudyIRJsonSchema() {
  return stripSafeIntegerBounds(z.toJSONSchema(llm.study, { io: "input" }));
}

/** Every concept in a draft, with its location, for resolution UIs and checks. */
export function draftConcepts(ir: DraftStudyIR): { path: string; cohortName: string; domainId: string; concept: DraftConcept }[] {
  const domainOf = (c: DraftCohortSpec) => (c.kind === "drug_new_user" ? "Drug" : "Condition");
  const cohorts: [string, DraftCohortSpec][] = [
    ["target", ir.target],
    ["comparator", ir.comparator],
    ...ir.outcomes.flatMap((o, i): [string, DraftCohortSpec][] => (o.kind === "phenotype" ? [] : [[`outcomes[${i}]`, o]])),
  ];
  return cohorts.flatMap(([path, cohort]) =>
    cohort.concepts.map((concept, i) => ({ path: `${path}.concepts[${i}]`, cohortName: cohort.name, domainId: domainOf(cohort), concept })),
  );
}

/** Concept IDs at or above this are placeholders for unresolved terms (never real OMOP IDs). */
export const PLACEHOLDER_CONCEPT_ID_BASE = 9_000_000_000_000;

function termHash(term: string): number {
  let h = 0;
  for (const ch of term.trim().toLowerCase()) h = (h * 31 + ch.codePointAt(0)!) % 1_000_000_007;
  return h;
}

/**
 * Replaces unresolved concepts with placeholders so the study-level checks can
 * run before every term is matched (e.g. to catch an inverted time at risk in an
 * LLM draft right away). The same term always gets the same placeholder ID, so
 * "target and comparator use the same concept set" is still detected.
 * Never compile the result.
 */
export function withPlaceholderConcepts(ir: DraftStudyIR): unknown {
  const fill = (cohort: DraftCohortSpec) => {
    const domainId = cohort.kind === "drug_new_user" ? "Drug" : "Condition";
    return {
      ...cohort,
      concepts: cohort.concepts.map((c) =>
        isResolved(c)
          ? c
          : {
              conceptId: PLACEHOLDER_CONCEPT_ID_BASE + termHash(c.conceptName),
              conceptName: c.conceptName,
              domainId,
              vocabularyId: "(unresolved)",
              conceptClassId: "",
              conceptCode: "",
              standardConcept: "S" as const,
              includeDescendants: c.includeDescendants,
            },
      ),
    };
  };
  return {
    ...ir,
    target: fill(ir.target),
    comparator: fill(ir.comparator),
    outcomes: ir.outcomes.map((o) => (o.kind === "phenotype" ? o : fill(o))),
  };
}
